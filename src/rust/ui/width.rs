//! Terminal column widths of characters.
//!
//! The tables are generated from `unicode-width` 0.2.2 and reproduce the width it gives every
//! character on its own and followed by U+FE0F VARIATION SELECTOR-16, so the layout of the
//! console output stays the same without the dependency.

use std::cmp::Ordering;

/// Returns how many terminal columns a character takes up on its own.
pub fn char_width(character: char) -> usize {
    // KHMER SIGN BEYYAL is the one character measured as three columns.
    if character == '\u{17d8}' {
        3
    } else if contains(ZERO_WIDTH, character) {
        0
    } else if contains(DOUBLE_WIDTH, character) {
        2
    } else {
        1
    }
}

/// Returns how many terminal columns a character takes up when U+FE0F VARIATION SELECTOR-16
/// follows it and asks for its emoji presentation.
pub fn emoji_presentation_width(character: char) -> usize {
    if contains(EMOJI_PRESENTATION, character) {
        2
    } else {
        char_width(character)
    }
}

fn contains(ranges: &[(u32, u32)], character: char) -> bool {
    let code = u32::from(character);

    ranges
        .binary_search_by(|&(start, end)| {
            if code < start {
                Ordering::Greater
            } else if code > end {
                Ordering::Less
            } else {
                Ordering::Equal
            }
        })
        .is_ok()
}

